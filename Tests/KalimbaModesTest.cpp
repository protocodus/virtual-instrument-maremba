// Derived two-span eigenmodes: boundary conditions, modal mass, independent
// finite-element frequencies, limiting cases, and actual release spectra.
#include "KalimbaModes.h"
#include "ModalExcitation.h"
#include <algorithm>
#include <cmath>
#include <cstdlib>
#include <iostream>

namespace {
constexpr double pi = 3.14159265358979323846;
void require(bool condition, const char* message) {
    if (!condition) { std::cerr << "FAIL: " << message << '\n'; std::exit(1); }
}

// Independent differentiation of the frozen analytic segment, divided by
// beta^order so residuals remain comparable across all eight modes.
double derivative(const maremba::KalimbaBeamSegment& s, double beta,
                  double span, double position, int order) {
    const double phase = beta * position + order * pi / 2;
    return s.ep * std::exp(beta * (position - span))
         + (order % 2 ? -1 : 1) * s.em * std::exp(-beta * position)
         + s.cosine * std::cos(phase) + s.sine * std::sin(phase);
}

// Scalar determinant of slope and moment matching after each segment's
// displacement at the bridge has been eliminated. Hyperbolic scaling avoids
// unnecessarily large products. No table entries are used by this equation.
double eigencondition(double k, double rear) {
    const double b = k * rear;
    // Divide out b^3 in the cantilever limit; direct subtraction of cos(b)
    // and sech(b) loses their first nonzero O(b^4) difference near b=0.
    const double a=b<.02 ? -b/6+b*b*b/12-173*std::pow(b,5)/5040
                        : (std::cos(b)-1/std::cosh(b))/(b*b*b);
    const double c=b<.02 ? -2./3+b*b/3-19*std::pow(b,4)/140
                        : (std::tanh(b)*std::cos(b)-std::sin(b))/(b*b*b);
    return a*(std::sin(k)-std::tanh(k)*std::cos(k))-c*(1/std::cosh(k)+std::cos(k));
}
double root(double lo, double hi, double rear) {
    require(eigencondition(lo,rear)*eigencondition(hi,rear)<0, "reference root bracket is invalid");
    for (int i=0;i<60;++i) {
        const double mid=.5*(lo+hi);
        if (eigencondition(lo,rear)*eigencondition(mid,rear)>0) lo=mid;
        else hi=mid;
    }
    return .5*(lo+hi);
}
template <class F> double integrate(F function, double lo, double hi, int count=2048) {
    double sum=0;
    for (int n=0;n<=count;++n) {
        const double x=lo+(hi-lo)*n/count;
        sum += function(x) * (n==0 || n==count ? 1 : n%2 ? 4 : 2);
    }
    return sum*(hi-lo)/(3*count);
}
double cantileverWeight(int mode,double position) {
    static constexpr double k[3]={1.875104068711961,4.694091132974175,7.854757438237613};
    const double sigma=(std::cosh(k[mode])+std::cos(k[mode]))/(std::sinh(k[mode])+std::sin(k[mode]));
    const double z=k[mode]*position;
    return (std::cosh(z)-std::cos(z)-sigma*(std::sinh(z)-std::sin(z)))
         * (mode==0 ? .65826598627927 : .5);
}
}

int main() {
    using namespace maremba;
    // Independent consistent-mass cubic-Hermite FEM: 200 elements over the
    // playing span, 60 behind the bridge. Generated by generate_kalimba_modes.py
    // from K phi=lambda M phi, with only clamp w/theta and bridge w constrained.
    constexpr double femBeta[8]={1.7553207618034377,4.4488990426302601,7.4957190889698317,
        10.512563394814711,13.287838059514501,14.785514463883075,17.05717109832964,20.009366793508168};
    double worstBoundary=0, worstMass=0, worstFEM=0, worstFootprint=0;
    for (int mode=0;mode<8;++mode) {
        const auto& m=kKalimbaBeamModes[mode];
        require(m.ratio>=1 && (mode==0 || m.ratio>kKalimbaBeamModes[mode-1].ratio), "modal order is not increasing");
        require(std::abs(m.ratio-std::pow(m.beta/kKalimbaBeamModes[0].beta,2))<1.e-12,
                "frequency ratio does not come from the same eigenmode as its shape");
        worstFEM=std::max(worstFEM,std::abs(m.beta/femBeta[mode]-1));
        require(std::abs(eigencondition(m.beta,kKalimbaRearSpan))<1.e-12,"frozen eigenvalue violates independent matching determinant");
        for (int d : {0,1}) worstBoundary=std::max(worstBoundary,std::abs(derivative(m.rear,m.beta,kKalimbaRearSpan,0,d)));
        for (int d : {2,3}) worstBoundary=std::max(worstBoundary,std::abs(derivative(m.playing,m.beta,1,0,d)));
        worstBoundary=std::max(worstBoundary,std::abs(derivative(m.rear,m.beta,kKalimbaRearSpan,kKalimbaRearSpan,0)));
        worstBoundary=std::max(worstBoundary,std::abs(derivative(m.playing,m.beta,1,1,0)));
        for (int d : {1,2}) {
            const double left=derivative(m.rear,m.beta,kKalimbaRearSpan,kKalimbaRearSpan,d);
            const double right=(d%2 ? -1 : 1)*derivative(m.playing,m.beta,1,1,d);
            worstBoundary=std::max(worstBoundary,std::abs(left-right));
        }
        for (int other=0;other<8;++other) {
            const auto product=[&](double x){return KalimbaFullModeShape(mode,x)*KalimbaFullModeShape(other,x);};
            const double mass=integrate(product,-kKalimbaRearSpan,0)+integrate(product,0,1);
            worstMass=std::max(worstMass,std::abs(mass-(mode==other ? 1.0 : 0.0)));
        }
        for (double x : {0.0,.05,.35,.65,.825,.95,1.0}) for(double width:{.0,.025,.065,.25}) {
            const double actual=KalimbaContactWeight(mode,x,width);
            require(std::isfinite(actual) && std::abs(actual)<1.5,"contact projection is unbounded");
            const double lo=std::max(0.,x-width/2),hi=std::min(1.,x+width/2);
            const double reference=width>0 ? integrate([&](double u){return KalimbaFullModeShape(mode,u);},lo,hi)/(hi-lo)*m.contactScale
                                           : KalimbaFullModeShape(mode,x)*m.contactScale;
            worstFootprint=std::max(worstFootprint,std::abs(actual-reference));
            require(actual==ModalContactWeight(mode,x,width,true),"tine excitation bypasses the derived geometry");
        }
    }
    require(worstBoundary<2.e-13,"clamp/free/bridge boundary conditions are not satisfied");
    require(worstMass<1.e-9,"two-span modes are not mass normalized and orthogonal");
    require(worstFEM<1.e-7,"analytical roots disagree with independent Hermite FEM");
    require(worstFootprint<1.e-10,"finite contact average disagrees with numerical integration");
    require(KalimbaModeRatio(0)==1 && std::abs(KalimbaContactWeight(0,.825,0)-1)<1.e-14,
            "fundamental pitch/default-position calibration changed");

    // Shrinking the rear segment gives a clamped-free playing span; compare
    // ratios rather than absolute roots, whose first correction is O(rear).
    const double tinyRear=.0001;
    const double k0=root(1.8,1.9,tinyRear),k1=root(4.6,4.8,tinyRear),k2=root(7.7,7.9,tinyRear);
    require(std::abs(std::pow(k1/k0,2)-6.266893025)<1.e-5
         && std::abs(std::pow(k2/k0,2)-17.547481937)<1.e-5,"cantilever limit is incorrect");
    // Equal spans factor into cos(k)=0 or tan(k)=tanh(k), independent of the
    // fixed .30 production table. This is an exact nontrivial geometry check.
    require(std::abs(root(1.4,1.7,1)-pi/2)<1.e-12
         && std::abs(root(3.8,4.1,1)-3.926602312047919)<1.e-12
         && std::abs(root(4.6,4.9,1)-3*pi/2)<1.e-12,"equal-span golden eigenvalues are incorrect");

    // Coherent pluck behaviour: moving along the playable portion changes
    // relative upper participation. A footprint spanning a modal node cancels
    // force while still touching moving material (positive contact loss).
    const double nearTip=KalimbaContactWeight(1,.98,0)/KalimbaContactWeight(0,.98,0);
    const double inner=KalimbaContactWeight(1,.65,0)/KalimbaContactWeight(0,.65,0);
    require(std::abs(nearTip-inner)>.4,"pluck position fails to select upper modal participation");
    double lo=.4,hi=.99;
    for(int i=0;i<60;++i){const double mid=.5*(lo+hi);if(KalimbaContactWeight(1,lo,0)*KalimbaContactWeight(1,mid,0)>0)lo=mid;else hi=mid;}
    const double node=.5*(lo+hi);
    require(std::abs(KalimbaContactWeight(1,node,0))<1.e-12
         && ModalContactParticipation(1,node,.1,true)>.001,"node cancellation erased physical contact participation");

    // Isolate the new derived geometry in a short velocity-after-release bank:
    // same f0, durations and readout weights as the cantilever reference. This
    // is an acoustic proxy, not a full-engine or listening-quality assertion.
    double delta=0,energy=0;
    constexpr double oldRatios[3]={1,6.266893025,17.547481937};
    constexpr double readout[3]={1,1.38,.79};
    for(int n=0;n<9600;++n){
        const double t=n/96000.;double oldSignal=0,newSignal=0;
        for(int m=0;m<3;++m){
            const double envelope=std::exp(-t*(m==0 ? 3.0 : m==1 ? 70.0 : 160.0));
            oldSignal+=envelope*readout[m]/oldRatios[m]*cantileverWeight(m,.98)*std::sin(2*pi*261.625565*oldRatios[m]*t);
            newSignal+=envelope*readout[m]/KalimbaModeRatio(m)*KalimbaContactWeight(m,.98,0)*std::sin(2*pi*261.625565*KalimbaModeRatio(m)*t);
        }
        delta+=(oldSignal-newSignal)*(oldSignal-newSignal);energy+=oldSignal*oldSignal;
    }
    const double change=10*std::log10(delta/energy);
    require(change>-35 && change<-8,"derived geometry is silent or overwhelms the fundamental in the release proxy");
    std::cout<<"KALIMBA worst_boundary="<<worstBoundary<<" worst_mass="<<worstMass
             <<" worst_fem_relative_beta="<<worstFEM<<" worst_contact_integral="<<worstFootprint
             <<" short_release_difference_db="<<change<<'\n';
    std::cout<<"Kalimba supported-beam contracts passed.\n";
}
