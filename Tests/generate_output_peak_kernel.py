#!/usr/bin/env python3
"""Deterministically generate the detector-only fractional interpolation FIR."""
import argparse
import math
from pathlib import Path
import struct


def i0(x):
    term = total = 1.0
    k = 1
    while True:
        term *= (x * x / 4) / (k * k)
        total += term
        if term < total * 1e-17:
            return total
        k += 1


def coefficients():
    result = []
    for fraction in (.25, .5, .75):
        values = []
        for tap in range(32):
            distance = tap - (15 + fraction)
            sinc = math.sin(math.pi * distance) / (math.pi * distance)
            window = i0(8.6 * math.sqrt(1 - (distance / 16) ** 2)) / i0(8.6)
            values.append(sinc * window)
        scale = sum(values)
        result.append([struct.unpack("f", struct.pack("f", v / scale))[0] for v in values])
    return result


def generated_header():
    rows = coefficients()
    bound = math.ceil(max(sum(abs(v) for v in row) for row in rows) * 1e6) / 1e6
    assert all(abs(sum(row) - 1) < 1e-7 for row in rows)
    assert rows[0] == rows[2][::-1] and rows[1] == rows[1][::-1]
    prefix = """#pragma once

// Generated by Tests/generate_output_peak_kernel.py. Four-times interpolation:
// three fractional phases plus the actual samples, 32 taps per phase, Kaiser
// beta 8.6. Rows run oldest to newest, evaluating positions 15.25/15.5/15.75.
// This is a detector only; the audible signal never passes through this FIR.
namespace maremba { namespace output_peak {
static constexpr int kTaps = 32;
// Rounded upward from the largest sum(abs(float coefficients)).
"""
    return (prefix + f"static constexpr double kMaximumL1 = {bound:.6f};\n"
            + "static constexpr float kPhases[3][kTaps] = {\n"
            + ",\n".join("    {" + ", ".join(f"{v:.9g}f" for v in row) + "}" for row in rows)
            + "\n};\n\n} } // namespace maremba::output_peak\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[1] / "Source/DSP/OutputPeakKernel.h")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generated_header()
    if args.check:
        if not args.output.is_file() or args.output.read_text() != expected:
            raise SystemExit(f"FAIL: generated kernel differs: {args.output}")
        print("PASS: interpolation kernel matches deterministic generator")
    else:
        args.output.write_text(expected)
        print(args.output)


if __name__ == "__main__":
    main()
