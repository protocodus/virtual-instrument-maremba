#!/usr/bin/env python3
"""Freeze SADIE II D1 directional filters for Maremba's declared capture scene.

Requires numpy, scipy and h5py only at generation time. Input is the exact
48 kHz SOFA from official SADIE II v2-2. Production uses no SOFA dependency.
Measured magnitudes are minimum-phase reconstructed; the residual interaural
phase slope supplies delay separately. This is a documented adaptation of
measured 1.2 m diffuse-field-equalized HRTFs, not an exact KU100 replica.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOFA_SHA256 = "9af7cb19531e52fb7ae8ec92621e6ab62b1d5fe584b3742be36699a0ddb0ccd4"
SOFA_URL = "https://zenodo.org/records/12092466/files/D1_HRIR_SOFA.zip?download=1"
FFT = 8192
TAPS = 160
RATE = 48000


def sha(path):
    return hashlib.sha256(pathlib.Path(path).read_bytes()).hexdigest()


def geometry():
    with tempfile.TemporaryDirectory(prefix="maremba-hrtf-geometry-") as temporary:
        path = pathlib.Path(temporary)
        source = path / "geometry.cpp"
        source.write_text(r'''#include "CaptureGeometry.h"
#include <cstdio>
int main() {
    auto h=maremba::CloseHeadCentre();
    std::printf("%.17g %.17g %.17g\n", h.x,h.y,h.z);
    for(int i=0;i<maremba::kCaptureSourceCount;++i) {
        auto p=maremba::CaptureSourcePosition(i);
        std::printf("%.17g %.17g %.17g\n",p.x,p.y,p.z);
    }
}
''')
        subprocess.run(["clang++", "-std=c++17", "-O2", "-I", str(ROOT / "DSP"),
                        str(source), "-o", str(path / "geometry")], check=True)
        rows = np.array([[float(x) for x in line.split()] for line in
                         subprocess.check_output([str(path / "geometry")], text=True).splitlines()])
    return rows[0], rows[1:]


def minimum_phase(log_magnitude):
    cepstrum = np.fft.irfft(log_magnitude, n=FFT, axis=-1)
    cepstrum[..., 1:FFT // 2] *= 2
    cepstrum[..., FFT // 2 + 1:] = 0
    spectrum = np.exp(np.fft.rfft(cepstrum, axis=-1))
    return np.fft.irfft(spectrum, n=FFT, axis=-1), spectrum


def spectral_data(impulse):
    spectrum = np.fft.rfft(impulse, n=FFT, axis=-1)
    logmag = np.log(np.maximum(np.abs(spectrum), 1e-9))
    impulse, minimum = minimum_phase(logmag)
    # Fit the interaural excess phase directly: common measurement delay and
    # common equalization cancel. A raw/min-phase peak cross-correlation can
    # choose a different pinna lobe in each ear and invent a centre-source ITD.
    phase = np.unwrap(np.angle(spectrum[1] * minimum[0] /
                               (spectrum[0] * minimum[1])), axis=-1)
    frequency = np.fft.rfftfreq(FFT, 1 / RATE)
    band = (frequency >= 200) & (frequency <= 2000)
    omega = 2 * np.pi * frequency[band] / RATE
    weight = np.sqrt(np.abs(spectrum[0, band] * spectrum[1, band]))
    fit = np.polyfit(omega, phase[band], 1, w=weight)
    residual_seconds = -float(fit[0]) / RATE
    fit_error = float(np.sqrt(np.average((phase[band] - np.polyval(fit, omega)) ** 2,
                                         weights=weight * weight)))
    return impulse, residual_seconds, fit_error


def emit_header(path, kernels, residual, indices, positions, source_hash, geometry_hash):
    lines = ["// Generated by Tests/generate_close_hrtf.py; do not edit.",
             "// Modified from SADIE II D1 (KU100), Copyright 2018 University of York.",
             "// Apache-2.0: see docs/licenses/SADIE-II-LICENSE.txt and SADIE-II-NOTICE.txt.",
             "// Phase-aligned minimum-phase HRIR interpolation; 160 taps, measured residual ITD separate.",
             "// 1.2 m, diffuse-field-equalized measurements; not raw capsule/SPL calibration.",
             f"// Source SOFA SHA256: {source_hash}", f"// CaptureGeometry SHA256: {geometry_hash}",
             "#pragma once", "#include <cstdint>", "namespace maremba {",
             f"constexpr int kCloseHrtfReferenceRate = {RATE};",
             f"constexpr int kCloseHrtfTaps = {TAPS};",
             f"constexpr int kCloseHrtfProfileCount = {len(kernels)};",
             f"constexpr int kCloseHrtfSourceCount = {len(indices)};",
             "struct CloseHrtfProfile { float residualItdSeconds; float impulse[2][kCloseHrtfTaps]; };",
             "static constexpr CloseHrtfProfile kCloseHrtfProfiles[kCloseHrtfProfileCount] = {"]
    def f(value):
        s = format(float(np.float32(value)), ".9g")
        return s + ("f" if "." in s or "e" in s else ".0f")
    for ir, delay in zip(kernels, residual):
        lines.append("    {" + f(delay) + ", {")
        for channel in ir:
            lines.append("        {" + ", ".join(f(value) for value in channel) + "},")
        lines.append("    }},")
    lines.extend(["};", "static constexpr std::uint16_t kCloseHrtfSourceProfile[kCloseHrtfSourceCount] = {"])
    for i in range(0, len(indices), 16):
        lines.append("    " + ", ".join(str(value) for value in indices[i:i+16]) + ",")
    lines.extend(["};", "} // namespace maremba", ""])
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text("\n".join(lines))
    temporary.replace(path)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sofa", type=pathlib.Path)
    parser.add_argument("--check", action="store_true", help="check frozen hashes and packaged license equality without SOFA/dependencies")
    parser.add_argument("--header", type=pathlib.Path, default=ROOT / "DSP/MeasuredCloseHrtf.h")
    parser.add_argument("--receipt", type=pathlib.Path,
                        default=ROOT / "docs/validation/capture-20260927/close-hrtf-generation.json")
    args = parser.parse_args()
    license_names = ("SADIE-II-LICENSE.txt", "SADIE-II-NOTICE.txt")
    if args.check:
        receipt = json.loads(args.receipt.read_text())
        assert receipt["header_sha256"] == sha(args.header), "generated header differs from receipt"
        assert receipt["generator_sha256"] == sha(__file__), "generator changed; regenerate assets"
        for name, digest in receipt["geometry_dependency_sha256"].items():
            assert sha(ROOT / "DSP" / name) == digest, f"geometry dependency changed: {name}"
        for name in license_names:
            canonical = ROOT / "docs/licenses" / name
            packaged = ROOT / "Resources/Private/Licenses" / name
            assert canonical.read_bytes() == packaged.read_bytes(), f"packaged license differs: {name}"
            assert receipt["license_sha256"][name] == sha(canonical), f"license receipt differs: {name}"
        print("Frozen Close HRTF hashes, geometry dependencies and packaged licenses match")
        return
    if args.sofa is None:
        parser.error("--sofa is required for generation (or use --check)")
    global h5py, np, scipy, ConvexHull
    import h5py
    import numpy as np
    import scipy
    from scipy.spatial import ConvexHull
    source_hash = sha(args.sofa)
    if source_hash != SOFA_SHA256:
        raise SystemExit("SOFA hash mismatch: use official SADIE II v2-2 D1 48kHz file")
    with h5py.File(args.sofa, "r") as source:
        pos = source["SourcePosition"][:]
        raw = source["Data.IR"][:]
        assert raw.shape == (8802, 2, 256)
        assert float(source["Data.SamplingRate"][0]) == RATE
        assert np.all(source["Data.Delay"][:] == 0)
        metadata = {key: (value.decode() if isinstance(value, bytes) else str(value))
                    for key, value in source.attrs.items()}
    radians = np.deg2rad(pos[:, :2])
    directions = np.column_stack((np.cos(radians[:, 1]) * np.cos(radians[:, 0]),
                                  np.cos(radians[:, 1]) * np.sin(radians[:, 0]),
                                  np.sin(radians[:, 1])))
    _, unique = np.unique(np.round(directions, 12), axis=0, return_index=True)
    unique.sort()
    directions = directions[unique]
    raw = raw[unique]
    hull = ConvexHull(directions)
    head, points = geometry()
    point_lookup = {}
    indices, kernels, delays, records = [], [], [], []
    cache = {}
    all_error, max_error = [], 0.0
    frequency = np.fft.rfftfreq(FFT, 1 / RATE)
    band = (frequency >= 100) & (frequency <= 18000)
    for point in points:
        key = tuple(point.tolist())
        if key in point_lookup:
            indices.append(point_lookup[key]); continue
        profile = len(kernels)
        point_lookup[key] = profile
        indices.append(profile)
        offset = point - head
        # Scene +Y is listener forward; scene -X is listener left. SOFA uses
        # +X forward and +Y left, with positive azimuth counter-clockwise.
        direction = np.array([offset[1], -offset[0], offset[2]])
        direction /= np.linalg.norm(direction)
        score = (hull.equations[:, :3] @ direction) / -hull.equations[:, 3]
        # A regular latitude/longitude grid contains coplanar quadrilaterals.
        # Qhull triangulates each; equal plane scores do not identify which
        # half contains this ray, so check all faces tied at the first hit.
        vertex = weight = None
        for face in np.flatnonzero(score >= np.max(score) - 1e-10):
            candidate = hull.simplices[face]
            barycentric = np.linalg.solve(directions[candidate].T, direction)
            barycentric /= np.sum(barycentric)
            if np.min(barycentric) >= -1e-7:
                vertex = candidate
                weight = np.maximum(barycentric, 0)
                weight /= np.sum(weight)
                break
        if vertex is None:
            raise RuntimeError("spherical interpolation left every enclosing triangle")
        for index in vertex:
            if int(index) not in cache:
                cache[int(index)] = spectral_data(raw[index])
        # Interpolate aligned minimum-phase impulse responses, not logarithmic
        # magnitudes: geometric interpolation of spectral zeros can create
        # long fractional-zero tails that cannot be represented by a short FIR.
        impulse = sum(w * cache[int(i)][0] for w, i in zip(weight, vertex))
        delay = sum(w * cache[int(i)][1] for w, i in zip(weight, vertex))
        exact = np.fft.rfft(impulse, n=FFT, axis=-1)
        result = impulse[:, :TAPS].copy()
        result[:, -8:] *= np.linspace(1, 0, 8)
        result = result.astype(np.float32)
        measured = np.abs(exact)
        error = np.abs(20 * np.log10(np.maximum(np.abs(np.fft.rfft(result, n=FFT, axis=-1)), 1e-9)
                                    / np.maximum(measured, 1e-9)))
        use = band[None, :] & (measured >= np.max(measured, axis=-1, keepdims=True) * 10**(-30/20))
        selected = error[use]
        all_error.extend(selected.tolist())
        max_error = max(max_error, float(np.max(selected)))
        kernels.append(result); delays.append(delay)
        records.append({"profile": profile, "position_m": point.tolist(),
                        "azimuth_elevation_deg": [float(np.rad2deg(np.arctan2(direction[1], direction[0]))),
                                                   float(np.rad2deg(np.arcsin(direction[2])))],
                        "source_measurement_indices": unique[vertex].tolist(), "weights": weight.tolist(),
                        "residual_itd_seconds": float(delay),
                        "maximum_vertex_excess_phase_fit_rms_radians": max(cache[int(i)][2] for i in vertex),
                        "minimum_retained_energy": float(np.min(np.sum(result**2, axis=-1) / np.sum(impulse**2, axis=-1))),
                        "max_magnitude_error_db": float(np.max(selected))})
    if max_error > 0.65:
        raise RuntimeError(f"160-tap truncation error {max_error:.3f}dB exceeds validated bound")
    geometry_hash = sha(ROOT / "DSP/CaptureGeometry.h")
    emit_header(args.header, kernels, delays, indices, points, source_hash, geometry_hash)
    for name in license_names:
        target = ROOT / "Resources/Private/Licenses" / name
        target.parent.mkdir(parents=True, exist_ok=True)
        temporary = target.with_suffix(target.suffix + ".tmp")
        temporary.write_bytes((ROOT / "docs/licenses" / name).read_bytes())
        temporary.replace(target)
    receipt = {"dataset": "SADIE II v2-2 D1 KU100", "dataset_doi": "10.5281/zenodo.12092466",
               "download_url": SOFA_URL, "sofa_sha256": source_hash, "sofa_metadata": metadata,
               "generator_sha256": sha(__file__), "geometry_sha256": geometry_hash,
               "license_sha256": {name: sha(ROOT / "docs/licenses" / name) for name in license_names},
               "geometry_dependency_sha256": {name: sha(ROOT / "DSP" / name) for name in
                                                ("CaptureGeometry.h", "MarimbaModel.h", "BarModes.h")},
               "generation_environment": {"python": sys.version, "numpy": np.__version__,
                                           "scipy": scipy.__version__, "h5py": h5py.__version__},
               "header_sha256": sha(args.header), "source_count": len(points), "profile_count": len(kernels),
               "reference_rate": RATE, "taps": TAPS, "fft_size": FFT,
               "processing": "homomorphic minimum phase at each measured vertex; spherical-triangle linear interpolation of aligned HRIRs; final8tap linear taper; float32; residual interaural excess-phase weighted slope200..2000Hz",
               "magnitude_error_band": "truncation/float32 against full interpolated aligned HRIR; 100..18000Hz, bins within30dB of each profile ear maximum; not a bound on angular/nearfield approximation",
               "magnitude_error_db_percentiles_50_95_99_100": np.quantile(all_error, [.5,.95,.99,1]).tolist(),
               "source_profile_indices": indices, "profiles": records,
               "limits": "Measured at1.2m, diffuse-field equalized and LF extended. Scene distance/flight adapts that directional response; no individualized/nearfield-perfect/exacthardware/SPL claim. Extra allpass phase discarded, residual ITD retained separately. No second capsule/head filter."}
    args.receipt.parent.mkdir(parents=True, exist_ok=True)
    args.receipt.write_text(json.dumps(receipt, indent=2) + "\n")
    print(json.dumps({key: receipt[key] for key in ("source_count", "profile_count", "taps", "magnitude_error_db_percentiles_50_95_99_100", "header_sha256")}, indent=2))

if __name__ == "__main__":
    main()
