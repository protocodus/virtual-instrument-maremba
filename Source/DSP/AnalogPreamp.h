#pragma once

#include "DspMath.h"
#include <algorithm>
#include <cmath>
#include <initializer_list>

namespace maremba {

class AnalogPreamp {
public:
    AnalogPreamp() {
        SetSampleRate(kReferenceRate);
        Reset();
    }

    void Reset() {
        mDcBlockInL = mDcBlockOutL = 0.0f;
        mDcBlockInR = mDcBlockOutR = 0.0f;
        mTiltLowL = mTiltLowR = 0.0f;
        mPreviousDriveL = mPreviousDriveR = 0.0f;
        mCachedDrive = -1.0f;
        mDriveCoefficients = {};
        mCachedWarmth = 2.0f;
        mLowGain = mHighGain = mSmoothLow = mSmoothHigh = 1.0f;
    }

    // Idle or reset: the tilt starts at its setting instead of ramping from
    // flat under the next attack.
    void SnapTone(float warmth) {
        mCachedWarmth = warmth;
        mLowGain = std::exp2(warmth);
        mHighGain = 1.0f / mLowGain;
        mSmoothLow = mLowGain;
        mSmoothHigh = mHighGain;
    }

    // Control rate: with a silent input (all mic levels at 0) the DC blocker and
    // the tilt low-pass decay into float subnormals and stay there (a subnormal
    // times a pole close to 1 rounds back to itself). Zero them first.
    void FlushTiny() {
        for (float* x : { &mDcBlockInL, &mDcBlockOutL, &mDcBlockInR, &mDcBlockOutR, &mTiltLowL, &mTiltLowR, &mPreviousDriveL, &mPreviousDriveR }) {
            if (std::abs(*x) < kTinyState) *x = 0.0f;
        }
    }

    // True when no filter state is subnormal (unit testing)
    bool HasNoSubnormalState() const {
        for (float x : { mDcBlockInL, mDcBlockOutL, mDcBlockInR, mDcBlockOutR, mTiltLowL, mTiltLowR, mPreviousDriveL, mPreviousDriveR }) {
            if (std::fpclassify(x) == FP_SUBNORMAL) return false;
        }
        return true;
    }

    void SetSampleRate(double sampleRate) {
        mSampleRate = sampleRate > 8000.0 ? sampleRate : kReferenceRate;
        mToneAlpha = static_cast<float>(1.0-std::exp(-1.0/(.005*mSampleRate)));
        mTiltAlpha = static_cast<float>(1.0 - std::exp(-kTwoPiD * 450.0 / mSampleRate));
        // DC blocker corner in Hz (was a fixed per-sample pole, i.e. a corner that moved with the rate)
        mDcPole = static_cast<float>(std::exp(-kTwoPiD * kDcBlockHz / mSampleRate));
    }

    // Main-bus preamplifier. The first 10% is exactly linear (+0.10 dB at
    // the factory setting). The remaining travel increases input drive by
    // up to 24 dB into a mildly asymmetric, rounded voltage-rail model.
    // Partial output compensation adds density without a matching peak jump.
    struct DriveCoefficients {
        float gain = 1.0f, compensation = 1.0f, cleanGain = 1.0f, wet = 0.0f;
        bool bypass = true;
    };
    static DriveCoefficients PrepareDrive(float drive) {
        drive = std::isfinite(drive) ? std::clamp(drive, 0.0f, 1.0f) : 0.1f;
        const float cleanGain = 1.0f + 0.12f * std::min(drive, 0.1f);
        if (drive <= 0.1f) return {1.0f, 1.0f, cleanGain, 0.0f, true};
        const float travel = (drive - 0.1f) / 0.9f;
        const float inputGain = std::exp2(4.0f * travel);
        const float onset = std::min((drive - 0.1f) / 0.12f, 1.0f);
        const float wet = onset * onset * (3.0f - 2.0f * onset);
        return {inputGain / kDriveRail,
                cleanGain * kDriveRail / (std::sqrt(inputGain) * (1.0f - kDriveBias * kDriveBias)),
                cleanGain, wet, false};
    }
    // Instantaneous transfer for calibration. Production uses the integral
    // average below, reducing aliases generated by the nonlinear curve.
    static float ApplyDrive(float sample, const DriveCoefficients& drive) {
        if (drive.bypass) return sample * drive.cleanGain;
        if (sample == 0.0f) return 0.0f;
        const double wet = (DriveCurve(static_cast<double>(sample) * drive.gain + kDriveBias)
                            - kDriveBiasOutput) * drive.compensation;
        return static_cast<float>(sample * drive.cleanGain
            + drive.wet * (wet - sample * drive.cleanGain));
    }
    static float ApplyDrive(float sample, float drive) {
        return ApplyDrive(sample, PrepareDrive(drive));
    }

    // Drive follows the complete Close/Room/Piezo mix. The direct captures
    // never enter this stage. DC removal and the existing Warmth tilt follow.
    void Process(float inL, float inR, float drive, float warmth, float& outL, float& outR) {
        if (drive != mCachedDrive) {
            mDriveCoefficients = PrepareDrive(drive);
            mCachedDrive = drive;
        }
        float satL = ProcessDrive(inL, mPreviousDriveL);
        float satR = ProcessDrive(inR, mPreviousDriveR);

        // DC Blocker (20 Hz). Runs continuously, so toggling the drive never
        // resumes from a stale state.
        float dcL = satL - mDcBlockInL + mDcPole * mDcBlockOutL;
        mDcBlockInL = satL;
        mDcBlockOutL = dcL;
        satL = dcL;

        float dcR = satR - mDcBlockInR + mDcPole * mDcBlockOutR;
        mDcBlockInR = satR;
        mDcBlockOutR = dcR;
        satR = dcR;

        // 2. Transparent Baxandall / Tilt Tone Filter (flat at warmth = 0.0).
        // The low band tracks continuously so re-enabling the tilt is click-free.
        mTiltLowL += mTiltAlpha * (satL - mTiltLowL);
        mTiltLowR += mTiltAlpha * (satR - mTiltLowR);
        // +/-6 dB shelf endpoints; cache exponentials at control changes and
        // smooth the actual gains over 5 ms, including transitions through flat.
        if (warmth != mCachedWarmth) {
            mCachedWarmth = warmth;
            mLowGain = std::exp2(warmth);
            mHighGain = 1.0f / mLowGain;
        }
        mSmoothLow += mToneAlpha * (mLowGain - mSmoothLow);
        mSmoothHigh += mToneAlpha * (mHighGain - mSmoothHigh);
        outL = mTiltLowL*mSmoothLow + (satL-mTiltLowL)*mSmoothHigh;
        outR = mTiltLowR*mSmoothLow + (satR-mTiltLowR)*mSmoothHigh;
    }

private:
    static constexpr float kDriveRail = 0.8f;
    static constexpr float kDriveBias = 0.08f;
    static constexpr double kDriveBiasOutput = static_cast<double>(kDriveBias)
        - static_cast<double>(kDriveBias) * kDriveBias * kDriveBias / 3.0;

    // A C1 soft clipper and its continuous primitive. This is an authored
    // preamp characteristic, not a claim to model a particular analog circuit.
    static double DriveCurve(double x) {
        if (x >= 1.0) return 2.0 / 3.0;
        if (x <= -1.0) return -2.0 / 3.0;
        return x - x * x * x / 3.0;
    }
    static double DrivePrimitive(double x) {
        const double ax = x < 0.0 ? -x : x;
        if (ax >= 1.0) return (2.0 / 3.0) * ax - 0.25;
        const double square = x * x;
        return square * (0.5 - square / 12.0);
    }
    static double AverageDriveCurve(double a, double b) {
        // Factoring the polynomial avoids cancellation around tiny samples.
        if (a >= -1.0 && a <= 1.0 && b >= -1.0 && b <= 1.0)
            return (a + b) * (0.5 - (a * a + b * b) / 12.0);
        if (a >= 1.0 && b >= 1.0) return 2.0 / 3.0;
        if (a <= -1.0 && b <= -1.0) return -2.0 / 3.0;
        const double delta = a - b;
        if (delta > -1.0e-6 && delta < 1.0e-6) return DriveCurve(0.5 * (a + b));
        return (DrivePrimitive(a) - DrivePrimitive(b)) / delta;
    }
    float ProcessDrive(float sample, float& previous) {
        const float prior = previous;
        previous = sample; // Advance even in bypass, so live Drive starts warm.
        const auto& drive = mDriveCoefficients;
        if (drive.bypass) return sample * drive.cleanGain;
        if (sample == 0.0f && prior == 0.0f) return 0.0f;
        const double a = static_cast<double>(sample) * drive.gain + kDriveBias;
        const double b = static_cast<double>(prior) * drive.gain + kDriveBias;
        // First-order antiderivative antialiasing (ADAA). Active Drive has
        // frequency-dependent/approximately half-sample phase delay; the
        // exact clean region has none. No new fixed host latency is added.
        const double wet = (AverageDriveCurve(a, b) - kDriveBiasOutput) * drive.compensation;
        const double clean = static_cast<double>(sample) * drive.cleanGain;
        return static_cast<float>(clean + drive.wet * (wet - clean));
    }
    float mPreviousDriveL = 0.0f, mPreviousDriveR = 0.0f;
    float mCachedDrive = -1.0f;
    DriveCoefficients mDriveCoefficients;

    static constexpr double kDcBlockHz = 20.0;
    static constexpr float kTinyState = 1.0e-20f;   // about -400 dB

    double mSampleRate = kReferenceRate;
    float mTiltAlpha = 0.031f;
    float mDcPole = 0.9986f;

    float mDcBlockInL = 0.0f;
    float mDcBlockOutL = 0.0f;
    float mDcBlockInR = 0.0f;
    float mDcBlockOutR = 0.0f;
    float mTiltLowL = 0.0f;
    float mTiltLowR = 0.0f;
    float mCachedWarmth = 2.0f;
    float mLowGain = 1.0f, mHighGain = 1.0f;
    float mSmoothLow = 1.0f, mSmoothHigh = 1.0f, mToneAlpha = .004f;
};

} // namespace maremba
